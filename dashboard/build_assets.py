#!/usr/bin/env python3
"""Build the two dependency-free UI modules into one classic-script request."""
import argparse,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parent
SOURCES=('sha256.js','helpers.js','transport.js')
TARGET=ROOT/'static/ui-helpers.js'
def bundle():
 return '/* Generated by build_assets.py; edit helpers.js or transport.js. */\n'+'\n'.join((ROOT/'static'/name).read_text() for name in SOURCES)
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();content=bundle()
 if a.check:
  if not TARGET.is_file() or TARGET.read_text()!=content:raise SystemExit('UI bundle is stale; run app/build_assets.py')
 else:
  if TARGET.is_symlink():raise RuntimeError('Refusing a symlink bundle')
  if not TARGET.exists() or TARGET.read_text()!=content:
   temp=TARGET.with_suffix('.js.tmp');temp.write_text(content);temp.replace(TARGET)
 print('UI bundle SHA256',hashlib.sha256(content.encode()).hexdigest(),'bytes',len(content.encode()))
if __name__=='__main__':main()
